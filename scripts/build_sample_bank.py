def build():
    interviews, foundations = [], []
    for topic, stage, title, definition, mechanism, example, boundary, q1, q2 in CONTENT:
        common = dict(difficulty='基础', stage=stage, topics=[topic], primary_topic=topic,
                      source_name='公开版独立编写的通用学习示例', source_ref='scripts/build_sample_bank.py#' + topic)
        answer = f'**定义 (Definition)**\n{definition}\n\n**工作机制 (Mechanism)**\n{mechanism}\n\n**使用场景与示例 (Example)**\n{example}\n\n**边界与误区 (Limitations)**\n{boundary}\n\n**学习检查**\n能够给出输入、处理中间状态和输出，并解释一种失败情况；不要只背术语。'
        if topic == 'python':
            answer += '\n\n**代码示例**\n```python\ndef squares(count):\n    # 每次迭代只产生一个平方数，不提前创建整个列表。\n    for number in range(count):\n        yield number * number\n\nvalues = squares(3)\nprint(next(values))  # 消费第一个值。\nprint(list(values))  # 只收集剩余值；此处会分配列表内存。\nprint(list(values))  # 迭代器已耗尽，不会自动从头开始。\n```\n\n**示例输出 (Example Output)**\n```text\n0\n[1, 4]\n[]\n```'
        foundations.append(dict(common, id=f'public-kb-{topic}-01', prompt=title, answer=answer, kind='基础知识', content_type='foundation'))
        for n, (prompt, direct) in enumerate((q1,q2),1):
            answer = f'**简答**\n{direct}\n\n**关联机制**\n{mechanism}\n\n**常见追问**\n怎样验证这个设计或判断？\n\n**追问解答**\n从具体输入和预期结果出发，构造正常、边界与失败样本，保留可重复的配置和观测结果。{boundary}'
            interviews.append(dict(common, id=f'public-iq-{topic}-{n:02}', prompt=prompt, answer=answer, kind='原理与工程题', content_type='interview'))
    return interviews, foundations

if __name__ == '__main__':
    interviews, foundations = build()
    folder = ROOT / 'data' / 'foundations'
    folder.mkdir(parents=True, exist_ok=True)
    for path, rows in ((ROOT/'data/questions.json', interviews), (folder/'basics.json', foundations)):
        path.write_text(json.dumps(rows, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print(f'Generated {len(interviews)} interview questions and {len(foundations)} foundation cards.')
